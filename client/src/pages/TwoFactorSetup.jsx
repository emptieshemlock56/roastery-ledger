import { useEffect, useState } from 'react';
import { api } from '../api.js';

/** Shows backup codes once, with ways to keep them. */
export function BackupCodes({ codes, onDone, doneLabel = 'Continue' }) {
  const [saved, setSaved] = useState(false);
  const textVersion = `Roastery Ledger backup codes\nEach code works once. Use one if you lose your phone.\n\n${codes.join('\n')}\n`;

  function download() {
    const url = URL.createObjectURL(new Blob([textVersion], { type: 'text/plain' }));
    const a = Object.assign(document.createElement('a'), { href: url, download: 'roastery-ledger-backup-codes.txt' });
    a.click();
    URL.revokeObjectURL(url);
  }

  return (
    <div className="stack">
      <p>
        <b>Save these backup codes now.</b> If you lose your phone, each code lets you sign in once. They won't be shown again.
      </p>
      <ol className="backup-codes">
        {codes.map((c) => (
          <li key={c}>
            <code>{c}</code>
          </li>
        ))}
      </ol>
      <div className="row">
        <button type="button" onClick={() => navigator.clipboard?.writeText(textVersion)}>
          Copy
        </button>
        <button type="button" onClick={download}>
          Download
        </button>
        <button type="button" onClick={() => window.print()}>
          Print
        </button>
      </div>
      <label className="inline">
        <input type="checkbox" checked={saved} onChange={(e) => setSaved(e.target.checked)} /> I've saved my backup codes somewhere safe
        (password manager, or printed and kept away from my phone)
      </label>
      {onDone && (
        <button className="primary" disabled={!saved} onClick={onDone}>
          {doneLabel}
        </button>
      )}
    </div>
  );
}

/** Walks someone through turning on authenticator-app codes. */
export default function TwoFactorSetup({ onEnabled, onCancel }) {
  const [setup, setSetup] = useState(null);
  const [code, setCode] = useState('');
  const [error, setError] = useState(null);
  const [busy, setBusy] = useState(false);
  const [showKey, setShowKey] = useState(false);
  const [result, setResult] = useState(null);

  useEffect(() => {
    api('/auth/2fa/setup', { method: 'POST', body: {} }).then(setSetup, (e) => setError(e.message));
  }, []);

  async function confirm(e) {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      setResult(await api('/auth/2fa/enable', { method: 'POST', body: { code } }));
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  }

  if (result) return <BackupCodes codes={result.backup_codes} onDone={() => onEnabled(result.user)} />;

  return (
    <form className="stack" onSubmit={confirm}>
      <ol className="steps">
        <li>
          Install an <b>authenticator app</b> on your phone if you don't have one: Google Authenticator, Microsoft Authenticator, 1Password,
          or the Passwords app on iPhone.
        </li>
        <li>
          In the app, choose <b>add</b> (often a <b>+</b> button), then <b>scan a QR code</b>, and point your phone at this code:
          {setup ? (
            // SVG generated by our own server from the setup link.
            <div className="qr" dangerouslySetInnerHTML={{ __html: setup.qr_svg }} />
          ) : (
            !error && <div className="muted">Loading…</div>
          )}
          {setup && (
            <button type="button" className="link small" onClick={() => setShowKey((s) => !s)}>
              Can't scan it? Type a key instead
            </button>
          )}
          {showKey && setup && (
            <p className="small">
              Choose "enter a setup key", and type: <code className="setup-key">{setup.secret.match(/.{1,4}/g).join(' ')}</code> (time-based)
            </p>
          )}
        </li>
        <li>
          Type the <b>6-digit code</b> the app now shows for Roastery Ledger:
          <input
            className="code-input"
            inputMode="numeric"
            autoComplete="one-time-code"
            placeholder="123456"
            value={code}
            onChange={(e) => setCode(e.target.value)}
            required
          />
        </li>
      </ol>
      {error && <div className="error">{error}</div>}
      <div className="row end">
        {onCancel && (
          <button type="button" onClick={onCancel}>
            Cancel
          </button>
        )}
        <button className="primary" disabled={busy || !setup}>
          {busy ? 'Checking…' : 'Turn on two-factor sign-in'}
        </button>
      </div>
    </form>
  );
}
